import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createMiaDirector } from './mia-director.js';
const script = JSON.parse(readFileSync(new URL('./dialogue.json', import.meta.url), 'utf8'));
let t = 0;const cues=[];
const director = createMiaDirector({script,onCue:c=>cues.push(c),now:()=>t,random:()=>0});
assert.equal(director.trigger('not_an_event'),null);
const first=director.trigger('game_start'); assert.equal(first.event,'game_start');
assert.equal(director.trigger('game_start'),null,'per-event cooldown');
t+=25000;
const m=director.trigger('match_3');assert.equal(m.event,'match_3');
assert.equal(director.trigger('match_3'),null,'no repeated event');
t+=25000;
const second=director.trigger('match_3');assert.notEqual(second.id,m.id,'avoid repeated line');
const h=director.trigger('hint_manual');assert.equal(h.event,'hint_manual','manual hints bypass global cooldown');
const combo=director.trigger('special_combo');assert.equal(combo.event,'special_combo');
assert.equal(director.trigger('match_4'),null,'routine match suppressed after major reaction');
const record=director.trigger('new_record');assert.equal(record.event,'new_record');
director.reset(); assert.ok(director.trigger('match_3'));
assert.equal(cues.length,7);
console.log('Mia cue scheduler tests passed:',cues.map(c=>c.id).join(', '));
