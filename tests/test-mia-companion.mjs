import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { MiaCompanion } from '../src/mia-companion.js';
const script = JSON.parse(await readFile(new URL('../assets/ui/mia/dialogue.json', import.meta.url), 'utf8'));
globalThis.fetch = async () => ({ ok: true, json: async () => script });
const el = () => ({ hidden: true, dataset: {}, textContent: '', src: '' });
const portrait = el(), expression = el(), bubble = el(), endLine = el();
const mia = new MiaCompanion({ portrait, expression, bubble, endLine });
await mia.scriptPromise;
assert.equal(mia.voiceEnabled, false);
assert.equal(mia.setVoiceEnabled(true), false, 'TTS unavailable should not be enabled');
mia.start('classic');
await Promise.resolve();
assert.equal(bubble.hidden, false, 'game start should show a caption');
mia.onCombo({ comboKind: 'special-swap', combo: 1, cellCount: 6 });
mia.onCombo({ combo: 1, cellCount: 3 });
await new Promise(resolve => setTimeout(resolve, 920));
assert.equal(mia.director.getState().lastAnyEvent, 'special_combo', 'highest priority wins');
assert.equal(bubble.hidden, false);
mia.react('hint_manual');
assert.equal(mia.director.getState().lastAnyEvent, 'hint_manual');
mia.setReducedMotion(true);
assert.equal(portrait.dataset.reducedMotion, 'true');
mia.finish(true);
assert.equal(endLine.textContent, 'Wowie! A new top score!');
assert.equal(bubble.hidden, true);
assert.equal(mia.active, false);
console.log('Mia companion integration event tests passed');
